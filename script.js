document.addEventListener("DOMContentLoaded", () => {
  // Set current year in footer
  const yearEl = document.getElementById("year");
  if (yearEl) {
    yearEl.textContent = new Date().getFullYear();
  }

  // Language switcher (with safe storage for file:// on mobile)
  const getSavedLang = () => {
    try {
      return localStorage.getItem("sanatTerziLang") === "en" ? "en" : "tr";
    } catch {
      return "tr";
    }
  };

  let currentLang = getSavedLang();
  const langButtons = document.querySelectorAll(".lang-btn");
  const langSwitch = document.querySelector(".lang-switch");

  const applyLanguage = (lang) => {
    currentLang = lang;
    try {
      localStorage.setItem("sanatTerziLang", lang);
    } catch {
      // Ignore storage error in restricted file:// contexts
    }
    document.documentElement.lang = lang;

    if (langSwitch) {
      langSwitch.setAttribute("data-active", lang);
    }

    const dict = translations[lang];
    if (dict.pageTitle) {
      document.title = dict.pageTitle;
    }

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key] !== undefined) {
        el.setAttribute("placeholder", dict[key]);
      }
    });

    langButtons.forEach((btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
  };

  langButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const selectedLang = btn.getAttribute("data-lang");
      if (selectedLang && selectedLang !== currentLang) {
        applyLanguage(selectedLang);
      }
    });
  });

  applyLanguage(currentLang);

  // Mobile menu toggle
  const mobileToggle = document.getElementById("mobileToggle");
  const mobileMenu = document.getElementById("mobileMenu");

  if (mobileToggle && mobileMenu) {
    const closeMenu = () => {
      mobileMenu.classList.remove("open");
      mobileToggle.setAttribute("aria-expanded", "false");
      mobileMenu.setAttribute("aria-hidden", "true");
    };

    mobileToggle.addEventListener("click", () => {
      const isOpen = mobileMenu.classList.toggle("open");
      mobileToggle.setAttribute("aria-expanded", String(isOpen));
      mobileMenu.setAttribute("aria-hidden", String(!isOpen));
    });

    mobileMenu.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", closeMenu);
    });

    document.addEventListener("click", (event) => {
      if (
        mobileMenu.classList.contains("open") &&
        !mobileMenu.contains(event.target) &&
        !mobileToggle.contains(event.target)
      ) {
        closeMenu();
      }
    });
  }

  // WhatsApp quick message form
  const whatsappForm = document.getElementById("whatsappForm");
  if (whatsappForm) {
    whatsappForm.addEventListener("submit", (event) => {
      event.preventDefault();
      const name = document.getElementById("customerName").value.trim();
      const serviceSelect = document.getElementById("serviceType");
      const service = serviceSelect.options[serviceSelect.selectedIndex].textContent.trim();
      const note = document.getElementById("customerNote").value.trim();

      const lines =
        currentLang === "en"
          ? [
              "Hello Sanat Terzi,",
              `Name: ${name || "-"}`,
              `Service: ${service}`
            ]
          : [
              "Merhaba Sanat Terzi,",
              `Adım: ${name || "-"}`,
              `Hizmet: ${service}`
            ];

      if (note) {
        lines.push(currentLang === "en" ? `Note: ${note}` : `Not: ${note}`);
      }

      const message = encodeURIComponent(lines.join("\n"));
      window.open(`https://wa.me/905356502690?text=${message}`, "_blank", "noopener,noreferrer");
    });
  }

  // Dynamic background switcher, step controller & scroll progress bar
  const scrollProgress = document.getElementById("scrollProgress");
  const bgSlides = document.querySelectorAll(".bg-slide");
  const bgSections = document.querySelectorAll("section[data-bg]");
  const stepDots = document.querySelectorAll(".step-dot");
  let activeBgIndex = 0;
  let isStepping = false;

  const setActiveStep = (index) => {
    if (!bgSlides[index]) return;
    activeBgIndex = index;
    bgSlides.forEach((slide, idx) => {
      slide.classList.toggle("active", idx === activeBgIndex);
      slide.classList.toggle("passed", idx === activeBgIndex - 1);
    });
    stepDots.forEach((dot, idx) => {
      dot.classList.toggle("active", idx === activeBgIndex);
    });
  };

  const goToStep = (index) => {
    const clamped = Math.max(0, Math.min(bgSections.length - 1, index));
    const targetSec = bgSections[clamped];
    if (!targetSec) return;

    isStepping = true;
    setActiveStep(clamped);

    const headerOffset = window.innerWidth <= 768 ? 60 : 76;
    const targetTop = targetSec.getBoundingClientRect().top + window.scrollY - headerOffset;
    window.scrollTo({ top: Math.max(0, targetTop), behavior: "smooth" });

    setTimeout(() => {
      isStepping = false;
    }, 750);
  };

  stepDots.forEach((dot, idx) => {
    dot.addEventListener("click", (event) => {
      event.preventDefault();
      goToStep(idx);
    });
  });

  let scrollTicking = false;
  const updateScrollEffects = () => {
    scrollTicking = false;
    const scrollTop = window.scrollY;
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;

    if (scrollProgress) {
      const progress = docHeight > 0 ? Math.min(1, Math.max(0, scrollTop / docHeight)) : 0;
      scrollProgress.style.transform = `scaleX(${progress})`;
    }

    if (!isStepping && bgSlides.length > 0 && bgSections.length > 0) {
      const probeY = window.innerHeight * 0.45;
      let targetIndex = 0;

      bgSections.forEach((sec) => {
        const rect = sec.getBoundingClientRect();
        if (rect.top <= probeY) {
          targetIndex = Number(sec.getAttribute("data-bg")) || 0;
        }
      });

      if (targetIndex !== activeBgIndex) {
        setActiveStep(targetIndex);
      }
    }
  };

  window.addEventListener(
    "scroll",
    () => {
      if (!scrollTicking) {
        scrollTicking = true;
        window.requestAnimationFrame(updateScrollEffects);
      }
    },
    { passive: true }
  );
  updateScrollEffects();

  // Scroll reveal animation
  const revealEls = document.querySelectorAll(".reveal");
  if ("IntersectionObserver" in window && revealEls.length > 0) {
    const observer = new IntersectionObserver(
      (entries, obs) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            obs.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.12, rootMargin: "0px 0px -30px 0px" }
    );

    revealEls.forEach((el) => observer.observe(el));
  } else {
    revealEls.forEach((el) => el.classList.add("is-visible"));
  }
});
